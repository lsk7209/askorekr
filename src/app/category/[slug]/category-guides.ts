export function getCategoryGuide(category: CategoryDetail): CategoryGuide {
  const base = GUIDE_BY_CATEGORY[category.slug] ?? {
    intro:
      "이 카테고리는 생활 환경과 관리 난이도를 함께 비교해 식물을 고를 수 있도록 정리한 허브 페이지입니다.",
    criteria: [
      { title: "환경 적합도", body: "빛, 온도, 습도, 배치 공간을 먼저 확인하세요." },
      { title: "관리 시간", body: "물주기와 잎 관리를 감당할 수 있는지 비교하세요." },
      { title: "안전성", body: "반려동물과 어린 자녀가 있다면 독성 메모를 함께 확인하세요." }
    ],
    tips: ["처음에는 쉬운 식물부터 시작하고 관찰 기록을 남기세요."]
  };
  const count = category.plants.length;

  return {
    ...base,
    faqs: [
      {
        question: `${category.title}은 초보자에게 적합한가요?`,
        answer: `${category.title}에는 현재 ${count}개의 식물이 정리되어 있습니다. 난이도 점수와 물주기, 빛 조건을 함께 비교하면 초보자에게 맞는 후보를 고르기 쉽습니다.`
      },
      {
        question: `${category.title}을 고를 때 가장 먼저 볼 기준은 무엇인가요?`,
        answer:
          "식물 이름보다 실제 배치할 장소의 빛, 온도, 통풍, 반려동물 접근 가능성을 먼저 확인하는 것이 좋습니다."
      },
      {
        question: "추천 목록은 어떤 기준으로 정렬되나요?",
        answer:
          "카테고리 목록은 서울 기준 기후 적합도 점수를 우선 반영해 정렬하고, 상세 페이지에서 난이도와 안전성 정보를 함께 제공합니다."
      }
    ]
  };
}
